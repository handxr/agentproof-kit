// The project side: render pieces for each target, then make the disk match.
import { createHash } from "node:crypto";
import { chmodSync, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, readlinkSync, renameSync, rmdirSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative } from "node:path";
import { ADAPTERS } from "./adapters/index.ts";
import { emptyLike, merge, ownedIds } from "./merge.ts";
import { skillFiles } from "./adapters/shared.ts";
import { ParseError, parseLock, parseManifest, parsePieceKey, splitKey } from "./parse.ts";
import { loadPiece, loadRegistry } from "./registry.ts";
import { resolvePieces } from "./resolve.ts";
import type { GeneratedFile, Lock, MergedFile, Manifest, Piece, Problem, ProblemCode, Registry, Scope, Target } from "./types.ts";

export const MANIFEST = "agents.json";
export const LOCK = "agents.lock";
const START = "<!-- agentproof-kit:start -->";
const END = "<!-- agentproof-kit:end -->";

const sha = (s: string) => `sha256-${createHash("sha256").update(s).digest("base64")}`;
const readJson = (path: string): unknown => JSON.parse(readFileSync(path, "utf8"));

const readRawManifest = (dir: string): Record<string, unknown> => {
  if (!existsSync(join(dir, MANIFEST))) throw new ParseError(`no ${MANIFEST} in ${dir}`, "manifest-missing", "agentproof-kit init --registry <src>");
  return readJson(join(dir, MANIFEST)) as Record<string, unknown>;
};
export const readManifest = (dir: string): Manifest => parseManifest(readRawManifest(dir));
export const readLock = (dir: string): Lock | null => (existsSync(join(dir, LOCK)) ? parseLock(readJson(join(dir, LOCK))) : null);

/**
 * Where one install lives. project: agents.json, the lock and the files all sit in the project dir.
 * user (`--global`): agents.json and the lock sit in $XDG_CONFIG_HOME/agentproof-kit, the files under $HOME.
 * dryRun: compute and return the changes, write nothing.
 */
export type Place = { readonly scope: Scope; readonly config: string; readonly root: string; readonly dryRun?: boolean };
export type Where = string | Place;
export const placeOf = (w: Where): Place => (typeof w === "string" ? { scope: "project", config: w, root: w } : w);
export function userPlace(env: NodeJS.ProcessEnv = process.env): Place {
  const root = env.HOME || homedir();
  return { scope: "user", root, config: env.XDG_CONFIG_HOME ? join(env.XDG_CONFIG_HOME, "agentproof-kit") : join(root, ".config", "agentproof-kit") };
}

/** Files that get the managed section. A project has one AGENTS.md; at user scope each agent reads its own file. */
const USER_DOCS: Partial<Record<Target, string>> = { claude: ".claude/CLAUDE.md", codex: ".codex/AGENTS.md" };

export type Rendered = { files: Map<string, GeneratedFile>; agentsMd: string; docs: string[]; unsupported: string[]; warnings: string[] };

/** Pure. Skills are written once, to .agents/skills. Two targets may emit the same path only with identical content. */
const SKILLS_DIR = ".agents/skills";

export function render(pieces: readonly Piece[], targets: readonly Target[], scope: Scope = "project"): Rendered {
  const files = new Map<string, GeneratedFile>(skillFiles(pieces, SKILLS_DIR));
  const sections = new Set<string>();
  const unsupported: string[] = [];
  const warnings: string[] = [];
  for (const target of targets) {
    const out = ADAPTERS[target].render(pieces, scope);
    for (const [path, f] of out.files) {
      const prev = files.get(path);
      if (prev && JSON.stringify(prev, mapJson) !== JSON.stringify(f, mapJson)) throw new ParseError(`${path}: targets disagree on content`);
      files.set(path, f);
    }
    if (out.agentsMd) sections.add(out.agentsMd);
    unsupported.push(...out.unsupported);
    warnings.push(...out.warnings);
  }
  const list = pieces.map((p) => `- \`${p.key}\` ${p.version}${p.description ? `: ${p.description}` : ""}`).join("\n");
  const agentsMd = [`## Agent kit`, ``, `Generated by agentproof-kit. Edit agents.json, then run \`agentproof-kit update\`.`, ``, list, ...[...sections].map((s) => `\n## Rules\n\n${s.trim()}`)].join("\n");
  const docs = scope === "project" ? ["AGENTS.md"] : targets.flatMap((t) => USER_DOCS[t] ?? []);
  return { files, agentsMd, docs, unsupported, warnings };
}

const mapJson = (_k: string, v: unknown) => (v instanceof Map ? [...v] : v);
const isMerged = (f: GeneratedFile): f is MergedFile => f.kind === "json" || f.kind === "toml" || f.kind === "lines";
const fileHash = (f: GeneratedFile) => (f.kind === "whole" ? sha(f.content) : f.kind === "link" ? `link:${f.target}` : null);
const sorted = <T>(entries: Iterable<[string, T]>) => [...entries].sort(([a], [b]) => a.localeCompare(b));

export function lockFor(reg: Registry, targets: readonly Target[], pieces: readonly Piece[], r: Rendered): Lock {
  return {
    lockfileVersion: 2,
    registry: { source: reg.source, commit: reg.commit },
    targets,
    pieces: Object.fromEntries(pieces.map((p) => [p.key, { version: p.version, hash: p.hash }])),
    files: Object.fromEntries(sorted(r.files).flatMap(([path, f]) => { const h = fileHash(f); return h ? [[path, h]] : []; })),
    owned: Object.fromEntries(sorted(r.files).flatMap(([path, f]) => (isMerged(f) ? [[path, ownedIds(f)]] : []))),
  };
}

const lockText = (lock: Lock) => `${JSON.stringify(lock, null, 2)}\n`;

export function mergeAgentsMd(existing: string, section: string): string {
  const block = `${START}\n${section.trim()}\n${END}`;
  const i = existing.indexOf(START), j = existing.indexOf(END);
  if (i >= 0 && j > i) return existing.slice(0, i) + block + existing.slice(j + END.length);
  return existing ? `${existing.trimEnd()}\n\n${block}\n` : `${block}\n`;
}

const readText = (dir: string, path: string) => (existsSync(join(dir, path)) ? readFileSync(join(dir, path), "utf8") : null);

/** Every shared file this render or the previous lock touches, merged with what is on disk now. */
function merges(dir: string, r: Rendered, previous: Lock | null) {
  const paths = new Set([...Object.keys(previous?.owned ?? {}), ...[...r.files].filter(([, f]) => isMerged(f)).map(([p]) => p)]);
  return [...paths].map((path) => {
    const f = r.files.get(path);
    const current = readText(dir, path);
    return { path, current, ...merge(path, current, f && isMerged(f) ? f : emptyLike(path), previous?.owned[path] ?? []) };
  });
}

/** Write only what differs, atomically. Returns the paths that changed. */
function writeIfChanged(dir: string, path: string, content: string, executable = false, dry = false): boolean {
  const abs = join(dir, path);
  const same = existsSync(abs) && readFileSync(abs, "utf8") === content;
  const modeOk = !executable || (existsSync(abs) && (statSync(abs).mode & 0o111) !== 0);
  if (same && modeOk) return false;
  if (dry) return true;
  mkdirSync(dirname(abs), { recursive: true });
  const tmp = `${abs}.agentproof-kit-tmp`;
  writeFileSync(tmp, content);
  if (executable) chmodSync(tmp, 0o755);
  renameSync(tmp, abs);
  return true;
}

const lexists = (abs: string) => { try { lstatSync(abs); return true; } catch { return false; } };
const linkAt = (abs: string) => (lexists(abs) && lstatSync(abs).isSymbolicLink() ? readlinkSync(abs) : null);

/** Remove a path and any parent directories it leaves empty, up to the project root. */
function remove(dir: string, path: string) {
  rmSync(join(dir, path), { force: true });
  for (let d = dirname(path); d !== "."; d = dirname(d)) {
    const abs = join(dir, d);
    if (!existsSync(abs) || readdirSync(abs).length) return;
    rmdirSync(abs);
  }
}

/** A link may replace nothing, its own old link, or an empty directory. Anything else is the user's. */
function linkClash(dir: string, path: string, target: string, previous: Lock | null): string | null {
  const abs = join(dir, path);
  if (!lexists(abs) || linkAt(abs) !== null) return null;
  const st = lstatSync(abs);
  const ours = (p: string) => p in (previous?.files ?? {});
  if (st.isDirectory() && readdirSync(abs, { recursive: true }).every((n) => ours(join(path, String(n))) || statSync(join(abs, String(n))).isDirectory())) return null;
  return `${path}: already exists and agentproof-kit did not write it (wanted a link to ${target}). Rename it, or drop the piece from agents.json.`;
}

function writeLink(dir: string, path: string, target: string, dry: boolean): boolean {
  const abs = join(dir, path);
  if (linkAt(abs) === target) return false;
  if (dry) return true;
  if (lexists(abs)) rmSync(abs, { recursive: true, force: true });
  mkdirSync(dirname(abs), { recursive: true });
  symlinkSync(target, abs);
  return true;
}

/** Derive the whole project state from (lock, rendered). Safe to run any number of times. */
export function apply(where: Where, lock: Lock, r: Rendered, previous: Lock | null): string[] {
  const { root: dir, config, dryRun: dry = false } = placeOf(where);
  const del = (path: string) => { if (!dry) remove(dir, path); };
  const changed: string[] = [];
  // Merge first: a clash with a hand-written entry throws before anything is written.
  const merged = merges(dir, r, previous);
  const clashes = [...r.files].flatMap(([path, f]) => (f.kind === "link" ? [linkClash(dir, path, f.target, previous)] : [])).filter((c) => c !== null);
  if (clashes.length) throw new ParseError(clashes.join("\n"), "conflict", null);
  for (const path of Object.keys(previous?.files ?? {})) {
    if (!r.files.has(path) && lexists(join(dir, path))) { del(path); changed.push(`- ${path}`); }
  }
  for (const [path, f] of r.files) {
    if (f.kind === "whole" && writeIfChanged(dir, path, f.content, f.executable, dry)) changed.push(path);
    if (f.kind === "link" && writeLink(dir, path, f.target, dry)) changed.push(path);
  }
  for (const m of merged) {
    if (m.content === null) { if (m.current !== null) { del(m.path); changed.push(`- ${m.path}`); } }
    else if (writeIfChanged(dir, m.path, m.content, false, dry)) changed.push(m.path);
  }
  for (const doc of r.docs) if (writeIfChanged(dir, doc, mergeAgentsMd(readText(dir, doc) ?? "", r.agentsMd), false, dry)) changed.push(doc);
  if (writeIfChanged(config, LOCK, lockText(lock), false, dry)) changed.push(relative(dir, join(config, LOCK)));
  return changed;
}

/** Re-resolve from the registry's newest content. Rewrites the lock and generated files. */
export function update(where: Where): string[] {
  return updateWith(where, readManifest(placeOf(where).config));
}

/**
 * Resolve and apply `manifest`, then write it to agents.json. The manifest is written last, so a
 * failure (bad piece, clash with a hand-written entry) leaves the project exactly as it was.
 */
function updateWith(where: Where, raw: unknown): string[] {
  const manifest = parseManifest(raw);
  const changed = applyManifest(where, manifest);
  const { root, config, dryRun } = placeOf(where);
  if (writeIfChanged(config, MANIFEST, `${JSON.stringify(raw, null, 2)}\n`, false, dryRun)) changed.unshift(relative(root, join(config, MANIFEST)));
  return changed;
}

/** Create agents.json and the files it implies, or nothing at all. */
export function init(where: Where, manifest: Record<string, unknown>): string[] {
  const path = join(placeOf(where).config, MANIFEST);
  if (existsSync(path)) throw new ParseError(`${path} already exists`, "manifest-exists", "agentproof-kit update");
  return updateWith(where, manifest);
}

/** Add pieces to agents.json. The manifest changes only if the update succeeds. */
export function add(where: Where, keys: readonly string[]): string[] {
  const raw = readRawManifest(placeOf(where).config);
  const m = parseManifest(raw);
  const added: Record<string, string[]> = Object.fromEntries(Object.entries(m.add).map(([k, v]) => [k, [...v]]));
  const removed: Record<string, string[]> = Object.fromEntries(Object.entries(m.remove).map(([k, v]) => [k, [...v]]));
  for (const k of keys) {
    const { type, id } = splitKey(parsePieceKey(k));
    const list = (added[type] ??= []);
    if (!list.includes(id)) list.push(id);
    if (removed[type]) removed[type] = removed[type].filter((x) => x !== id);
  }
  return updateWith(where, { ...raw, add: added, remove: removed });
}

/**
 * Drop pieces. A piece listed in `add` leaves that list. A piece that comes from a preset goes into
 * `remove`. The update then deletes only the files and entries the lock says agentproof-kit wrote.
 */
export function removePieces(where: Where, keys: readonly string[]): string[] {
  const raw = readRawManifest(placeOf(where).config);
  const m = parseManifest(raw);
  const installed = readLock(placeOf(where).config)?.pieces ?? {};
  const lists = (l: typeof m.add): Record<string, string[]> => Object.fromEntries(Object.entries(l).map(([k, v]) => [k, [...v]]));
  const added = lists(m.add), removed = lists(m.remove);
  for (const k of keys) {
    const key = parsePieceKey(k);
    const { type, id } = splitKey(key);
    const fromAdd = added[type]?.includes(id) ?? false;
    if (!fromAdd && !(key in installed)) throw new ParseError(`${key} is not installed`, "not-installed", "agentproof-kit list");
    if (fromAdd) added[type] = added[type]!.filter((x) => x !== id);
    if (key in installed && !(removed[type] ??= []).includes(id)) removed[type]!.push(id);
  }
  return updateWith(where, { ...raw, add: added, remove: removed });
}

function applyManifest(where: Where, manifest: Manifest): string[] {
  const { scope, config } = placeOf(where);
  const reg = loadRegistry(manifest.registry, config);
  const keys = resolvePieces(manifest, reg.presets, new Set(reg.index.keys()));
  const pieces = keys.map((k) => loadPiece(reg, k));
  const r = render(pieces, manifest.targets, scope);
  return apply(where, lockFor(reg, manifest.targets, pieces, r), r, readLock(config));
}

/** Load exactly what the lock names. Fails if the registry content no longer matches the lock. */
function lockedPieces(dir: string, lock: Lock): { reg: Registry; pieces: Piece[]; drift: string[] } {
  const reg = loadRegistry(lock.registry.source, dir, lock.registry.commit);
  const drift: string[] = [];
  const pieces = Object.entries(lock.pieces).map(([k, want]) => {
    const p = loadPiece(reg, parsePieceKey(k));
    if (p.hash !== want.hash) drift.push(`${k}: registry content differs from agents.lock`);
    return p;
  });
  return { reg, pieces, drift };
}

/** Make the project match the lock. Never moves to newer registry content. */
export function sync(where: Where): string[] {
  const { scope, config } = placeOf(where);
  const lock = readLock(config);
  if (!lock) {
    readRawManifest(config); // with neither file, the first fix is init
    throw new ParseError(`no ${LOCK} in ${config}`, "lock-missing", "agentproof-kit update");
  }
  const { pieces, drift } = lockedPieces(config, lock);
  if (drift.length) throw new ParseError(drift.join("\n"), "registry-changed", "agentproof-kit update");
  return apply(where, lock, render(pieces, lock.targets, scope), lock);
}

export type CheckResult = { ok: boolean; problems: Problem[]; warnings: string[] };

const drifted = (message: string) => problem("drift", message, "agentproof-kit sync");
const problem = (code: ProblemCode, message: string, fix: string | null): Problem => ({ code, message, fix });

export function check(where: Where, env: NodeJS.ProcessEnv = process.env): CheckResult {
  const { scope, config, root: dir } = placeOf(where);
  const problems: Problem[] = [];
  const manifest = readManifest(config);
  const lock = readLock(config);
  if (!lock) return { ok: false, problems: [problem("lock-missing", `no ${LOCK} in ${config}`, "agentproof-kit update")], warnings: [] };

  // Outdated lock: the manifest asks for a different set, source or targets.
  const { reg, pieces, drift } = lockedPieces(config, lock);
  problems.push(...drift.map((d) => problem("registry-changed", d, "agentproof-kit update")));
  const wanted = resolvePieces(manifest, reg.presets, new Set(reg.index.keys()));
  const locked = Object.keys(lock.pieces).sort();
  if (manifest.registry !== lock.registry.source) problems.push(problem("lock-outdated", `registry is ${lock.registry.source} in ${LOCK}, ${manifest.registry} in ${MANIFEST}`, "agentproof-kit update"));
  if (wanted.join() !== locked.join()) problems.push(problem("lock-outdated", `pieces out of date (${MANIFEST} wants ${wanted.length}, ${LOCK} has ${locked.length})`, "agentproof-kit update"));
  if (manifest.targets.join() !== lock.targets.join()) problems.push(problem("lock-outdated", "targets out of date", "agentproof-kit update"));

  // Drift: whole files must match what the lock renders. In shared files only the owned entries count.
  const r = render(pieces, lock.targets, scope);
  for (const [path, f] of r.files) {
    if (f.kind === "link") {
      const at = linkAt(join(dir, path));
      if (at === null) problems.push(lexists(join(dir, path)) ? drifted(`${path} is not a link to ${f.target}`) : drifted(`${path} missing`));
      else if (at !== f.target) problems.push(drifted(`${path} points to ${at}, not ${f.target}`));
      continue;
    }
    const current = readText(dir, path);
    if (current === null) problems.push(drifted(`${path} missing`));
    else if (f.kind === "whole" && current !== f.content) problems.push(drifted(`${path} edited`));
  }
  try {
    for (const m of merges(dir, r, lock)) problems.push(...m.drift.map((d) => drifted(`${m.path} ${d}`)));
  } catch (e) {
    if (!(e instanceof ParseError)) throw e;
    problems.push(problem("conflict", e.message, null));
  }
  for (const doc of r.docs) {
    const text = readText(dir, doc) ?? "";
    if (mergeAgentsMd(text, r.agentsMd) !== text) problems.push(drifted(`${doc} managed section`));
  }

  // Secrets: every env var an MCP server names must be set.
  for (const p of pieces) {
    if (p.body.type !== "mcp") continue;
    const s = p.body.server;
    for (const name of s.kind === "stdio" ? s.env : s.bearerTokenEnv ? [s.bearerTokenEnv] : []) {
      if (!env[name]) problems.push(problem("env-missing", `${name} not set (needed by ${p.key})`, `export ${name}=<value>`));
    }
  }
  // A piece installed both globally and here loads twice in most agents.
  const warnings = [...r.warnings, ...r.unsupported.map((u) => `unsupported: ${u}`)];
  const global = scope === "project" ? readLock(userPlace(env).config) : null;
  for (const k of Object.keys(lock.pieces)) if (global && k in global.pieces) warnings.push(`${k} is installed both globally and in this project`);
  // Cursor also reads .claude/skills, where the Claude link points at the same folder.
  if (lock.targets.includes("cursor") && lock.targets.includes("claude") && pieces.some((p) => p.body.type === "skills")) {
    warnings.push("cursor lists each skill twice: it reads both .agents/skills and .claude/skills (same files, no conflict)");
  }
  return { ok: problems.length === 0, problems, warnings };
}
